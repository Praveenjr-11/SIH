/**
 * Returns revenue villages for a given district and taluk.
 * Falls back to generic revenue village sectors if not explicitly listed.
 */
export function getRevenueVillagesForTaluk(district: string, taluk: string): string[] {
  const normDist = (district || '').toLowerCase().trim().replace(/[^a-z0-9]/g, '');
  const normTaluk = (taluk || '').toLowerCase().trim().replace(/[^a-z0-9]/g, '');
  const cleanTaluk = (taluk || '').toLowerCase().replace(/\s+(taluk|subdistrict)$/i, '').trim();
  const cleanNormTaluk = cleanTaluk.replace(/[^a-z0-9]/g, '');

  // Try direct key
  const directKey = `${normDist}:${normTaluk}`;
  if (TN_TALUK_VILLAGES[directKey]) return TN_TALUK_VILLAGES[directKey];

  // Try cleaned taluk key
  const cleanKey = `${normDist}:${cleanNormTaluk}`;
  if (TN_TALUK_VILLAGES[cleanKey]) return TN_TALUK_VILLAGES[cleanKey];

  // Try fuzzy matching in dictionary
  for (const [k, list] of Object.entries(TN_TALUK_VILLAGES)) {
    const [d, t] = k.split(':');
    if (d === normDist || normDist.includes(d) || d.includes(normDist)) {
      if (t === cleanNormTaluk || t.includes(cleanNormTaluk) || cleanNormTaluk.includes(t)) {
        return list;
      }
    }
  }

  // Generate realistic revenue villages for this taluk
  const tName = taluk.replace(/\s+(taluk|subdistrict)$/i, '').trim();
  return [
    `${tName} Town (Kasba)`,
    `${tName} North`,
    `${tName} South`,
    `${tName} East`,
    `${tName} West`,
    `${tName} Agraharam`,
    `${tName} Pudur`,
    `${tName} Kottai`,
    `${tName} Medu`,
    `${tName} Patti`
  ];
}
